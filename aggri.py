    def growth_rate(temp, humidity, moisture):
        if 20.0 <= temp >= 30.0:
            temp = 1.0

        if temp < 10.0 or temp > 40.0:
            temp = 0.1

        else:
            temp = 0.6

        if 20.0 <= moisture <= 40.0:
            moisture = 1.0
        elif moisture < 15.0 or moisture > 45.0:
            moisture = 0.2
        else:
            moisture = 0.6

        if 50.0 <= humidity <= 75.0:
            humidity = 1.0
        else:
            humidity = 0.6

        growth_pct = (temp * 0.40 + moisture * 0.40 + humidity * 0.20) * 100.0
        return round(growth_pct, 1) 

